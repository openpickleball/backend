def _list(name: str) -> list[str]:
    """Split a comma-separated variable, stripping entries, dropping blanks."""
    return [item.strip() for item in _raw(name).split(",") if item.strip()]


def _database(url: str) -> dict[str, object]:
    """Parse DATABASE_URL, failing fast without echoing the value.

    Only a scheme django-environ knows, in scheme://host form, with a
    database name is accepted. django-environ alone accepts unknown
    schemes as engine names and some malformed URLs with no name.
    """
    scheme, separator, _ = url.partition("://")
    config: dict[str, object] = {}
    if separator and scheme in environ.Env.DB_SCHEMES:
        # django-environ warns with the parsed config, password included,
        # when it cannot find an engine. Silence that; we raise our own.
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            try:
                config = environ.Env.db_url_config(url)
            except ValueError:
                config = {}
    if not config.get("ENGINE") or not config.get("NAME"):
        raise ImproperlyConfigured(
            "DATABASE_URL is not a database URL. Use the form "
            "postgres://USER:PASSWORD@HOST:PORT/NAME (see .env.example)."
        )
    return config


def _is_redis_url(url: str) -> bool:
    """Return whether url is a REDIS_URL that redis-py reads as written."""
    # redis-py matches the scheme case-sensitively.
    if not url.startswith(("redis://", "rediss://")):
        return False
    # redis-py lets query arguments override settings, TLS verification
    # included, so no query string or fragment is allowed.
    if "?" in url or "#" in url:
        return False
    try:
        parts = urlsplit(url)
        # Raises ValueError when the port is not a number up to 65535.
        port = parts.port
    except ValueError:
        return False
    if not parts.hostname:
        return False
    # kombu splits a broker URL on ";" into failover hosts.
    if ";" in parts.hostname:
        return False
    # redis-py reads port 0 as unset and uses 6379.
    if port is not None and not 1 <= port <= 65535:
        return False
    # redis-py reads a database that is not a number as 0.
    db = parts.path.removeprefix("/")
    return db == "" or (db.isascii() and db.isdigit())


def _redis_url(url: str) -> str:
    """Check REDIS_URL, failing fast without echoing the value.

    Accepted: redis://[USER:PASSWORD@]HOST[:PORT][/DB], or rediss:// for
    TLS. The scheme is lowercase, a given port is 1 to 65535, and DB is a
    number. A query string or fragment is refused.
    """
    # The check catches its own errors, so none is chained to this one.
    if not _is_redis_url(url):
        raise ImproperlyConfigured(
            "REDIS_URL is not a Redis URL. Use the form "
            "redis://HOST:PORT/DB, or rediss:// for TLS (see .env.example)."
        )
    return url


# An exact browser origin: a lowercase http or https scheme, a host (a DNS
# name or a bracketed IPv6 address), and an optional port with no leading
# zero. Nothing else: no path, trailing slash, query, fragment, user info,
# or wildcard. Browsers leave out the scheme's default port (443 for
# https, 80 for http), so an origin that names it could never match.
_ORIGIN = re.compile(
    r"(?P<scheme>https?)://"
    r"(?:[a-z0-9-]+(?:\.[a-z0-9-]+)*|\[[0-9a-f:.]+\])"
    r"(?::(?P<port>[1-9][0-9]{0,4}))?"
)


def _is_origin(value: str) -> bool:
    """Return whether value is exactly scheme://host[:port]."""
    match = _ORIGIN.fullmatch(value)
    if match is None:
        return False
    port = match.group("port")
    if port is None:
        return True
    default_port = 443 if match.group("scheme") == "https" else 80
    return int(port) <= 65535 and int(port) != default_port


def _cors_origins(name: str) -> list[str]:
    """Read a list of exact origins, failing fast without echoing it.

    django-cors-headers checks the entries only in a system check, and
    gunicorn runs none, so a bad entry is refused here at startup.
    """
    origins = _list(name)
    if not all(_is_origin(origin) for origin in origins):
        raise ImproperlyConfigured(
            f"{name} has an entry that is not an origin. List exact origins, "
            "comma-separated, each a scheme (http or https), a host, and an "
            "optional port that is not the scheme's default, with no path, "
            "trailing slash, or wildcard (see .env.example)."
        )
    return origins


def _celery_broker_url(url: str) -> str:
    """Return a checked REDIS_URL in the form kombu reads as one broker.

    kombu splits a broker URL on ";" into failover hosts, even inside the
    password. The host cannot hold one (see _is_redis_url), so encoding
    ";" in the user and password as %3B leaves one broker. kombu decodes
    it back, so the password is unchanged.
    """
    scheme, _, rest = url.partition("://")
    userinfo, at, host = rest.rpartition("@")
    if not at:
        return url
    return f"{scheme}://{userinfo.replace(';', '%3B')}@{host}"


