def _raw(name: str) -> str:
    """Return a variable's literal value, or '' when it is unset."""
    return os.environ.get(name, "")


def _required(name: str) -> str:
    """Return a required variable, stripped, failing fast when blank."""
    value = _raw(name).strip()
    if not value:
        raise ImproperlyConfigured(
            f"Set the {name} environment variable (see .env.example)."
        )
    return value


def _list(name: str) -> list[str]:
    """Split a comma-separated variable, stripping entries, dropping blanks."""
    return [item.strip() for item in _raw(name).split(",") if item.strip()]


def _database(url: str) -> dict[str, object]:
    """Parse DATABASE_URL, failing fast without echoing the value.

    Only a scheme django-environ knows, in scheme://host form, with a
    database name is accepted. django-environ alone accepts unknown
    schemes as engine names and some malformed URLs with no name.
    """
    scheme, separator, _ = url.partition("://")
    config: dict[str, object] = {}
    if separator and scheme in environ.Env.DB_SCHEMES:
        # django-environ warns with the parsed config, password included,
        # when it cannot find an engine. Silence that; we raise our own.
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            try:
                config = environ.Env.db_url_config(url)
            except ValueError:
                config = {}
    if not config.get("ENGINE") or not config.get("NAME"):
        raise ImproperlyConfigured(
            "DATABASE_URL is not a database URL. Use the form "
            "postgres://USER:PASSWORD@HOST:PORT/NAME (see .env.example)."
        )
    return config


def _is_redis_url(url: str) -> bool:
    """Return whether url is a REDIS_URL that redis-py reads as written."""
    # redis-py matches the scheme case-sensitively.
    if not url.startswith(("redis://", "rediss://")):
        return False
    # redis-py lets query arguments override settings, TLS verification
    # included, so no query string or fragment is allowed.
    if "?" in url or "#" in url:
        return False
    try:
        parts = urlsplit(url)
        # Raises ValueError when the port is not a number up to 65535.
        port = parts.port
    except ValueError:
        return False
    if not parts.hostname:
        return False
    # redis-py reads port 0 as unset and uses 6379.
    if port is not None and not 1 <= port <= 65535:
        return False
    # redis-py reads a database that is not a number as 0.
    db = parts.path.removeprefix("/")
    return db == "" or (db.isascii() and db.isdigit())


def _redis_url(url: str) -> str:
    """Check REDIS_URL, failing fast without echoing the value.

    Accepted: redis://[USER:PASSWORD@]HOST[:PORT][/DB], or rediss:// for
    TLS. The scheme is lowercase, a given port is 1 to 65535, and DB is a
    number. A query string or fragment is refused.
    """
    # The check catches its own errors, so none is chained to this one.
    if not _is_redis_url(url):
        raise ImproperlyConfigured(
            "REDIS_URL is not a Redis URL. Use the form "
            "redis://HOST:PORT/DB, or rediss:// for TLS (see .env.example)."
        )
    return url


